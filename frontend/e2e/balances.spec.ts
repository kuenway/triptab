import { expect, test } from "@playwright/test";
import { openExpense, openSection } from "./trip-navigation";

test("net balances, accessible external confirmation and stale transfer recovery", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/register");
  await page.getByLabel("Display name").fill("Alice");
  await page.getByLabel("Email", { exact: true }).fill(`balances-${Date.now()}@example.com`);
  await page.getByLabel("Password", { exact: true }).fill("TripTab balances test 123");
  await page.getByRole("button", { name: "Register", exact: true }).click();
  await page.getByRole("button", { name: "+ New trip", exact: true }).click();
  await page.getByLabel("Trip name").fill("Balances confirmation smoke");
  await page.getByRole("button", { name: "Create trip" }).click();
  await expect(page).toHaveURL(/\/trips\/[^/]+$/);
  const tripId = page.url().split("/").pop()!;
  const guest = "Bob with a very long traveler name that wraps on mobile";
  await openSection(page, "Tripmates");
  await page.getByLabel("Tripmate name").fill(guest);
  await page.getByRole("button", { name: "Add tripmate" }).click();
  await expect(page.getByRole("group", { name: `Tripmate ${guest}` })).toBeVisible();
  await openSection(page, "Expenses");
  const form = await openExpense(page);
  await form.getByLabel("Description").fill("Shared hotel");
  await form.getByLabel("Amount (NT$)").fill("246912");
  await form.getByRole("button", { name: "Add expense", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await openSection(page, "Balances");
  const balances = page.getByRole("region", { name: "Balances", exact: true });
  const transfers = page.getByRole("region", { name: "Suggested transfers", exact: true });
  await expect(balances.getByText("You are owed", { exact: true })).toBeVisible();
  await expect(balances.locator(".balance-personal")).toContainText("NT$123,456");
  await expect(balances.locator(".balance-row").filter({ hasText: guest })).toContainText("Owes NT$123,456");
  await expect(transfers.getByRole("heading", { name: `${guest} to You` })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Record payment" })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const trigger = transfers.getByRole("button", { name: /^Mark settled/ });
  await trigger.scrollIntoViewIfNeeded();
  const box = (await trigger.boundingBox())!;
  const nav = (await page.getByRole("navigation", { name: "Trip sections" }).boundingBox())!;
  expect(box.height).toBeGreaterThanOrEqual(44);
  expect(box.y + box.height).toBeLessThanOrEqual(nav.y);
  await page.screenshot({ path: testInfo.outputPath("balances-mobile.png"), fullPage: true });
  const suggestionsPath = `/api/v1/groups/${tripId}/settlement-suggestions`;
  const confirmPath = `${suggestionsPath}/confirm`;
  const initial = (await (await page.request.get(suggestionsPath)).json()).suggestions[0];
  const tuple = { from_member_id: initial.from_member_id, to_member_id: initial.to_member_id, amount: initial.amount };
  const { csrf_token } = await (await page.request.get("/api/v1/auth/me")).json();
  const headers = { Origin: "http://127.0.0.1:3100", "X-CSRF-Token": csrf_token };

  // Native modal contains keyboard focus; Cancel/Escape return to the transfer.
  await trigger.focus();
  await page.keyboard.press("Enter");
  const dialog = page.getByRole("dialog", { name: "Mark this transfer as settled?" });
  await expect(dialog).toContainText("outside TripTab");
  await expect(dialog).toContainText("TripTab does not transfer money.");
  await expect(dialog.getByRole("button", { name: "Cancel" })).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(dialog.getByRole("button", { name: "Confirm settled" })).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(dialog.getByRole("button", { name: "Cancel" })).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(dialog.getByRole("button", { name: "Confirm settled" })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(trigger).toBeFocused();
  expect(await (await page.request.get(`/api/v1/groups/${tripId}/settlements`)).json()).toHaveLength(0);
  await trigger.click();
  await dialog.getByRole("button", { name: "Cancel" }).click();
  await expect(trigger).toBeFocused();

  // Desktop uses the centered workspace and a compact confirmation dialog.
  await page.setViewportSize({ width: 1280, height: 900 });
  const left = (await balances.boundingBox())!;
  const right = (await transfers.boundingBox())!;
  expect(right.x).toBeGreaterThan(left.x + left.width);
  expect(Math.abs(right.y - left.y)).toBeLessThan(2);
  await page.screenshot({ path: testInfo.outputPath("balances-desktop.png"), fullPage: true });
  await trigger.click();
  const modal = (await dialog.boundingBox())!;
  expect(modal.width).toBeLessThanOrEqual(480);
  expect(Math.abs(modal.x + modal.width / 2 - 640)).toBeLessThan(2);
  await dialog.screenshot({ path: testInfo.outputPath("settlement-confirmation.png") });
  const confirmed = page.waitForResponse(response => response.request().method() === "POST" && new URL(response.url()).pathname === confirmPath);
  await dialog.getByRole("button", { name: "Confirm settled" }).click();
  expect((await confirmed).status()).toBe(201);
  await expect(page.getByText("Settlement confirmed.", { exact: true })).toBeVisible();
  await expect(page.getByText("Everyone is settled up.", { exact: true })).toBeVisible();
  await expect(trigger).toHaveCount(0);
  const stale = await page.request.post(confirmPath, { data: tuple, headers });
  expect(stale.status()).toBe(409);
  expect(stale.headers()["cache-control"]).toBe("no-store");
  expect(await (await page.request.get(`/api/v1/groups/${tripId}/settlements`)).json()).toHaveLength(1);
  await page.getByRole("link", { name: "View settlement history" }).click();
  await expect(page.getByRole("region", { name: "History", exact: true })).toContainText(`${guest} settled with You`);

  // A second client consumes the next suggestion while this dialog is open.
  await openSection(page, "Expenses");
  const second = await openExpense(page);
  await second.getByLabel("Description").fill("Shared taxi");
  await second.getByLabel("Amount (NT$)").fill("600");
  await second.getByRole("button", { name: "Add expense", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await openSection(page, "Balances");
  await trigger.click();
  const next = (await (await page.request.get(suggestionsPath)).json()).suggestions[0];
  const otherClient = await page.context().newPage();
  try {
    const consumed = await otherClient.request.post(confirmPath, { data: { from_member_id: next.from_member_id, to_member_id: next.to_member_id, amount: next.amount }, headers });
    expect(consumed.status()).toBe(201);
  } finally { await otherClient.close(); }
  let confirmations = 0;
  page.on("request", request => { if (request.method() === "POST" && new URL(request.url()).pathname === confirmPath) confirmations++; });
  const conflict = page.waitForResponse(response => response.request().method() === "POST" && new URL(response.url()).pathname === confirmPath);
  await dialog.getByRole("button", { name: "Confirm settled" }).click();
  expect((await conflict).status()).toBe(409);
  await expect(page.getByText(/This settlement suggestion has changed/)).toBeVisible();
  await expect(page.getByText("Everyone is settled up.", { exact: true })).toBeVisible();
  await expect(dialog).toHaveCount(0);
  expect(confirmations).toBe(1);
  const final = await (await page.request.get(`/api/v1/groups/${tripId}/balances`)).json();
  expect(final.balances.every((balance: { amount: number }) => balance.amount === 0)).toBe(true);
  expect(await (await page.request.get(`/api/v1/groups/${tripId}/settlements`)).json()).toHaveLength(2);
});
