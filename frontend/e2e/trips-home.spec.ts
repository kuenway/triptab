import { expect, test } from "@playwright/test";

test("Trips home is list-first, creates destinations and retains navigation without N+1 reads", async ({ page }, testInfo) => {
  const email = `home-${Date.now()}@example.com`, password = "TripTab home test password 123";
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/register");
  await page.getByLabel("Display name").fill("Home organizer");
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Register", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your trips", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "No trips yet.", exact: true })).toBeVisible();
  await expect(page.getByRole("navigation", { name: "Trip sections" })).toHaveCount(0);
  await expect(page.getByLabel("Trip name")).toHaveCount(0);
  for (const target of [page.getByRole("button", { name: "Log out", exact: true }), page.getByRole("button", { name: "+ New trip", exact: true }), page.locator(".wordmark")]) expect((await target.boundingBox())!.height).toBeGreaterThanOrEqual(44);
  await page.screenshot({ path: testInfo.outputPath("home-empty-mobile.png") });
  const trigger = page.getByRole("button", { name: "+ New trip", exact: true });
  await trigger.focus(); await page.keyboard.press("Enter");
  const dialog = page.getByRole("dialog", { name: "New trip", exact: true });
  await expect(dialog.getByLabel("Trip name")).toBeFocused();
  await page.keyboard.press("Escape"); await expect(dialog).toHaveCount(0); await expect(trigger).toBeFocused();
  const names = ["Japan 2027", "A long trip name ".repeat(10).trim()];
  const urls: string[] = [];
  for (const name of names) {
    await trigger.click(); await dialog.getByLabel("Trip name").fill(name);
    await dialog.getByRole("button", { name: "Create trip", exact: true }).click();
    await expect(page).toHaveURL(/\/trips\/[^/]+$/);
    await expect(page.getByRole("heading", { name: "Expenses", exact: true })).toBeVisible();
    urls.push(page.url());
    await page.getByRole("link", { name: "← All trips", exact: true }).click();
    await expect(page.getByRole("link", { name, exact: true })).toBeVisible();
  }
  const reads: string[] = [];
  page.on("request", request => { const path = new URL(request.url()).pathname; if (request.method() === "GET" && path.startsWith("/api/v1/")) reads.push(path); });
  await page.reload();
  await expect(page.getByRole("list", { name: "Your trips" }).getByRole("link")).toHaveCount(2);
  expect(reads.sort()).toEqual(["/api/v1/auth/me", "/api/v1/groups"]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  for (const link of await page.getByRole("list", { name: "Your trips" }).getByRole("link").all()) expect((await link.boundingBox())!.height).toBeGreaterThanOrEqual(44);
  await page.screenshot({ path: testInfo.outputPath("home-list-mobile.png"), fullPage: true });
  await page.getByRole("link", { name: names[0], exact: true }).click();
  await expect(page).toHaveURL(urls[0]!); await expect(page.getByRole("heading", { name: "Expenses", exact: true })).toBeVisible();
  await page.goBack(); await expect(page.getByRole("heading", { name: "Your trips", exact: true })).toBeVisible();
  await page.goto(urls[1]!); await expect(page.getByRole("heading", { name: "Expenses", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "← All trips", exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect(page.getByRole("list", { name: "Your trips" }).getByRole("link")).toHaveCount(2);
  const shell = await page.locator(".trips-home").boundingBox();
  expect(shell!.width).toBeLessThanOrEqual(856); expect(Math.abs(shell!.x + shell!.width / 2 - 640)).toBeLessThan(2);
  await page.screenshot({ path: testInfo.outputPath("home-list-desktop.png") });
  await trigger.click(); const box = await dialog.boundingBox();
  expect(box!.width).toBeLessThanOrEqual(480); expect(Math.abs(box!.x + box!.width / 2 - 640)).toBeLessThan(2);
  await page.screenshot({ path: testInfo.outputPath("home-dialog-desktop.png") });
  await page.getByLabel("Trip name").focus(); await page.keyboard.press("Tab");
  await expect(dialog.getByRole("button", { name: "Cancel", exact: true })).toBeFocused();
  await page.keyboard.press("Tab"); await expect(dialog.getByRole("button", { name: "Create trip", exact: true })).toBeFocused();
  await page.keyboard.press("Shift+Tab"); await page.keyboard.press("Shift+Tab");
  await expect(dialog.getByLabel("Trip name")).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  const close = dialog.getByRole("button", { name: "Close new trip dialog", exact: true });
  await expect(close).toBeFocused();
  expect(await dialog.evaluate(element => element.matches(":modal"))).toBe(true);
  await trigger.evaluate(element => element.focus());
  await expect(close).toBeFocused();
  await page.keyboard.press("Escape"); await expect(trigger).toBeFocused();
  await page.setViewportSize({ width: 375, height: 480 }); await trigger.click();
  const mobile = await dialog.boundingBox(); expect(mobile!.width).toBe(375); expect(mobile!.y + mobile!.height).toBeLessThanOrEqual(480);
  await dialog.getByLabel("Trip name").fill("Keyboard viewport draft");
  await expect(dialog.getByRole("button", { name: "Create trip", exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("home-dialog-mobile.png") });
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Log out" }).click();
  await page.getByLabel("Email", { exact: true }).fill(email); await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await expect(page.getByRole("list", { name: "Your trips" }).getByRole("link")).toHaveCount(2);
});

test("Trips home keeps read errors and creation validation local", async ({ page }) => {
  await page.goto("/register"); await page.getByLabel("Display name").fill("Retry organizer");
  await page.getByLabel("Email", { exact: true }).fill(`home-errors-${Date.now()}@example.com`);
  await page.getByLabel("Password", { exact: true }).fill("TripTab home test password 123");
  await page.getByRole("button", { name: "Register", exact: true }).click();
  await expect(page.getByRole("heading", { name: "No trips yet.", exact: true })).toBeVisible();
  let release!: () => void; const gate = new Promise<void>(done => { release = done; });
  await page.route("**/api/v1/groups", async route => { await gate; await route.fulfill({ status: 503, contentType: "application/json", body: '{"detail":"Read failure"}' }); });
  await page.reload(); await expect(page.getByText("Loading trips…", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Your trips", exact: true })).toBeVisible(); release();
  await expect(page.getByRole("button", { name: "Retry trips", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "No trips yet.", exact: true })).toHaveCount(0);
  await page.unroute("**/api/v1/groups"); await page.getByRole("button", { name: "Retry trips", exact: true }).click();
  await expect(page.getByRole("heading", { name: "No trips yet.", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "+ New trip", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "New trip", exact: true }); await dialog.getByLabel("Trip name").fill("Validation draft");
  await page.route("**/api/v1/groups", route => route.fulfill({ status: 422, contentType: "application/json", body: '{"detail":"Trip name rejected"}' }));
  await dialog.getByRole("button", { name: "Create trip", exact: true }).click();
  await expect(dialog.getByRole("alert")).toHaveText("Trip name rejected"); await expect(dialog.getByLabel("Trip name")).toHaveValue("Validation draft");
  await expect(dialog.getByLabel("Trip name")).toHaveAttribute("aria-invalid", "true");
  await page.unroute("**/api/v1/groups"); await page.keyboard.press("Escape");
});
