import { expect, test } from "@playwright/test";
import { openExpense, openSection } from "./trip-navigation";

test("ledger-first entry, shared editing, history and responsive native dialog remain accessible", async ({ page }, testInfo) => {
  const suffix = `${Date.now()}-${Math.random().toString(36).slice(2)}`;
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/register");
  await page.getByLabel("Display name").fill("Alice");
  await page.getByLabel("Email", { exact: true }).fill(`ledger-${suffix}@example.com`);
  await page.getByLabel("Password", { exact: true }).fill("TripTab ledger test password 123");
  await page.getByRole("button", { name: "Register", exact: true }).click();
  await page.getByRole("button", { name: "+ New trip", exact: true }).click();
  await page.getByLabel("Trip name").fill(`Ledger ${suffix}`);
  await page.getByRole("button", { name: "Create trip" }).click();
  await expect(page).toHaveURL(/\/trips\/[^/]+$/);
  const tripId = new URL(page.url()).pathname.split("/").pop()!;
  await expect(page.getByRole("heading", { name: "No expenses yet." })).toBeVisible();
  await expect(page.getByLabel("Description")).toHaveCount(0);
  await openSection(page, "Tripmates");
  const names = ["Bob", "Charlie", "A traveler with a deliberately long display name", ...Array.from({ length: 8 }, (_, i) => `Guest ${i + 1}`)];
  for (const name of names) {
    await page.getByLabel("Tripmate name").fill(name);
    await page.getByRole("button", { name: "Add tripmate", exact: true }).click();
    await expect(page.getByRole("group", { name: `Tripmate ${name}`, exact: true })).toBeVisible();
  }
  await openSection(page, "Expenses");
  const members = await (await page.request.get(`/api/v1/groups/${tripId}/members`)).json();
  const ownerId = members.find((m: { role: string }) => m.role === "owner").id;
  const trigger = page.getByRole("button", { name: "Add expense", exact: true });
  const nav = page.getByRole("navigation", { name: "Trip sections" });
  const addBox = await trigger.boundingBox(), navBox = await nav.boundingBox();
  expect(addBox!.y + addBox!.height).toBeLessThan(navBox!.y);
  await page.keyboard.press("Tab"); await trigger.focus();
  expect(await trigger.evaluate(e => getComputedStyle(e).outlineStyle)).toBe("solid");
  await page.keyboard.press("Enter");
  const dialog = page.getByRole("dialog", { name: "Add expense", exact: true });
  await expect(dialog.getByLabel("Description")).toBeFocused();
  await expect(dialog.getByLabel("Paid by")).toHaveValue(ownerId);
  await expect(dialog.getByRole("radio", { name: "Equal", exact: true })).toBeChecked();
  for (const name of ["Alice", ...names]) await expect(dialog.getByRole("checkbox", { name, exact: true })).toBeChecked();
  expect(await dialog.getByLabel("When did it happen?").inputValue()).toMatch(/^\d{4}-\d\d-\d\dT\d\d:\d\d$/);
  const mobile = await dialog.boundingBox();
  expect(mobile!.width).toBe(375); expect(mobile!.y + mobile!.height).toBeCloseTo(812, 0);
  await nav.getByRole("link", { name: "Balances", exact: true }).evaluate(e => (e as HTMLElement).focus());
  await expect(dialog.getByLabel("Description")).toBeFocused();
  await page.keyboard.press("Shift+Tab"); await page.keyboard.press("Shift+Tab");
  expect(await page.evaluate(() => document.activeElement?.closest("dialog") !== null)).toBe(true);
  const description = "A long dinner description that still leaves the six-digit total readable on mobile";
  await dialog.getByLabel("Description").focus(); await page.keyboard.type(description);
  await dialog.getByLabel("Amount (NT$)").focus(); await page.keyboard.type("123456");
  const fieldsBox = await dialog.locator(".form-fields").boundingBox();
  const footerBox = await dialog.locator(".expense-form > .payment-actions").boundingBox();
  expect(fieldsBox!.y + fieldsBox!.height).toBeLessThanOrEqual(footerBox!.y + 1);
  await page.screenshot({ path: testInfo.outputPath("add-mobile.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Add expense", exact: true }).focus(); await page.keyboard.press("Enter");
  await expect(dialog).toHaveCount(0); await expect(trigger).toBeFocused();
  const current = page.getByRole("group", { name: "Current expenses", exact: true });
  const row = current.locator("article").filter({ hasText: description });
  await expect(row.getByRole("heading", { name: description })).toBeVisible();
  await expect(row).toContainText("NT$123,456"); await expect(row).toContainText(`You paid · ${members.length} tripmates`);
  await expect(page.getByRole("heading", { name: "Today", exact: true })).toBeVisible();
  const stored = await (await page.request.get(`/api/v1/groups/${tripId}/expenses`)).json();
  const share = stored[0].splits.find((s: { member_id: string }) => s.member_id === ownerId).amount;
  await expect(row).toContainText(`Your share NT$${share.toLocaleString("en-US")}`);
  await expect(row.getByText("Equal split", { exact: true })).not.toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await row.scrollIntoViewIfNeeded();
  const rowBox = await row.boundingBox(), floating = await trigger.boundingBox();
  expect(rowBox!.y + rowBox!.height).toBeLessThan(floating!.y);
  await page.screenshot({ path: testInfo.outputPath("ledger-mobile.png"), fullPage: true });

  await row.getByRole("button", { name: "Edit", exact: true }).focus(); await page.keyboard.press("Enter");
  const edit = page.getByRole("dialog", { name: "Edit expense", exact: true });
  await expect(edit.getByLabel("Amount (NT$)")).toHaveValue("123456");
  await edit.getByLabel("Amount (NT$)").fill("123457"); await edit.getByLabel("Reason", { exact: true }).fill("Correct receipt");
  await edit.getByRole("button", { name: "Save changes", exact: true }).focus(); await page.keyboard.press("Enter");
  await expect(edit).toHaveCount(0); await expect(current.locator("article")).toHaveCount(1); await expect(current).toContainText("NT$123,457");
  await current.getByRole("link", { name: "View edit history", exact: true }).click();
  await expect(page.locator("details.financial-history")).toContainText("Correct receipt");
  await expect(page.locator("details.financial-history")).toContainText("NT$123,456");
  await current.getByRole("button", { name: "Delete expense", exact: true }).focus(); await page.keyboard.press("Enter");
  const confirmation = current.getByRole("form", { name: "Delete expense", exact: true });
  await expect(confirmation.getByLabel("Note (optional)")).not.toHaveAttribute("required");
  for (const width of [375, 1280]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await confirmation.screenshot({ path: testInfo.outputPath(`delete-${width}.png`) });
  }
  await page.setViewportSize({ width: 375, height: 812 });
  await confirmation.getByRole("button", { name: "Confirm delete expense", exact: true }).focus(); await page.keyboard.press("Enter");
  await expect(current.locator("article")).toHaveCount(0);
  await openSection(page, "Balances");
  await expect(page.getByRole("region", { name: "Balances", exact: true })).toContainText("Everyone is settled up.");
  await openSection(page, "History"); await page.getByRole("heading", { name: description + " removed" }).locator("..").locator("..").locator("summary").click();
  const removed = page.getByRole("heading", { name: description + " removed" }).locator("..").locator("..");
  await expect(removed).not.toContainText("Note:");
  await expect(removed).not.toContainText("Reason:");
  const historyView = page.getByRole("region", { name: "History", exact: true });
  await expect(historyView.getByRole("heading", { name: description + " added", exact: true })).toBeVisible();
  await expect(historyView.getByRole("heading", { name: description + " edited", exact: true })).toBeVisible();
  await expect(historyView.getByRole("heading", { name: description + " removed", exact: true })).toBeVisible();
  await historyView.locator("details[open] > summary").click();
  await historyView.screenshot({ path: testInfo.outputPath("history-mobile.png") });
  await page.setViewportSize({ width: 1280, height: 900 });
  await historyView.screenshot({ path: testInfo.outputPath("history-desktop.png") });
  await page.setViewportSize({ width: 375, height: 812 });
  await openSection(page, "Expenses");

  const exact = await openExpense(page); await expect(exact.getByLabel("Description")).toHaveValue("");
  await exact.getByRole("radio", { name: "Exact amounts", exact: true }).check();
  await exact.getByLabel("Description").fill("Exact scrolling check"); await exact.getByLabel("Amount (NT$)").fill(String(members.length));
  for (const name of ["Alice", ...names]) await exact.getByLabel(`${name} allocation`, { exact: true }).fill("1");
  const fields = exact.locator(".form-fields"); expect(await fields.evaluate(e => e.scrollHeight > e.clientHeight)).toBe(true);
  await fields.evaluate(e => { e.scrollTop = e.scrollHeight; });
  const submitBox = await exact.getByRole("button", { name: "Add expense", exact: true }).boundingBox();
  expect(submitBox!.y + submitBox!.height).toBeLessThanOrEqual(812);
  await exact.getByRole("button", { name: "Add expense", exact: true }).click(); await expect(exact).toHaveCount(0);
  await expect(current).toContainText("Exact scrolling check");

  const draft = await openExpense(page); await draft.getByLabel("Description").fill("Keep this draft");
  page.once("dialog", async d => { expect(d.message()).toContain("Discard this expense draft?"); await d.dismiss(); });
  await page.keyboard.press("Escape"); await expect(draft.getByLabel("Description")).toHaveValue("Keep this draft");
  page.once("dialog", d => d.accept()); await draft.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(draft).toHaveCount(0);
  await page.setViewportSize({ width: 1280, height: 900 });
  const desktop = await openExpense(page); const box = await desktop.boundingBox();
  expect(box!.width).toBeLessThanOrEqual(640); expect(box!.x + box!.width / 2).toBeCloseTo(640, 0);
  expect(box!.y).toBeGreaterThan(0); expect(box!.y + box!.height).toBeLessThan(900);
  await page.screenshot({ path: testInfo.outputPath("add-desktop.png"), fullPage: true });
  await page.keyboard.press("Escape"); await expect(desktop).toHaveCount(0); await expect(trigger).toBeFocused();
  await page.screenshot({ path: testInfo.outputPath("ledger-desktop.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
